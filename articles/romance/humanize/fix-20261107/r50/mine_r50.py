#!/usr/bin/env python3
"""My tested change of r50 as a layer after r41/MINE-R41.json: MINE-R50.json, which whole/build.py applies.

His whole-article check of the r49 drafts (RESULTS-whole-r49.json) read Human with every window Human; two windows of
draft A were Medium, the same two one-sentence windows as in r39, and a Medium window is work to do (lesson
romance-2026-11-23i). Each is a sentence Pangram made a segment of its own:

- live 20 ("Affection and the simmer"), its last line "If every affectionate touch becomes a bid for sex, affection
  itself can start feeling like pressure." By itself the paragraph read AI Detected, 41%, that line AI-Generated
  (https://www.pangram.com/history/36aa6a6d-b5c1-4bba-8a68-129dcee268f9). It is way 6 of his fixes (a closing line that
  sounds wise) and way 16 (the line before already says it). Joined to the line it explains (way 8) and said plainly:
  "..., or she'll start treating every touch like a sales pitch." The paragraph read Human High
  (https://www.pangram.com/history/52ff7f0c-e151-4e8d-a553-fc4282ee3be5), and its section, one window
  (https://www.pangram.com/history/27c3b372-bc6e-4443-b057-e593fd1b9821).
- live 33 ("Situationships"), its opening line "And then there's the situationship, which is hard to define because
  that's basically the point." The paragraph read Human High by itself as it was; the line is joined to the sentence it
  introduces with ", but" (way 8), his words kept. The paragraph read Human High
  (https://www.pangram.com/history/722d3172-fb10-4237-97be-d89a690f5d31), and its section, one window
  (https://www.pangram.com/history/7ff558af-740d-40f9-8dcc-5475da271f17).

Whether the whole-article check still makes either a window of its own is for his next run of draft A to show.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
FIX = HERE.parent
repl = {int(k): v for k, v in json.loads((FIX / 'whole' / 'REPLACEMENTS.json').read_text(encoding='utf-8')).items()}
if (HERE / 'MINE-R50.json').exists():   # take this layer back out of REPLACEMENTS.json first
    for ch in reversed(json.loads((HERE / 'MINE-R50.json').read_text(encoding='utf-8'))['changes']):
        now = repl[ch['live']]
        k = now.index(ch['after'][0])
        repl[ch['live']] = now[:k] + [ch['before']] + now[k + 1:]
post = {}
for line in (FIX / 'live-check' / 'LIVE-POST-BLOCKS-20261123.jsonl').read_text(encoding='utf-8').splitlines():
    r = json.loads(line)
    if r.get('n') is not None:
        post[r['n']] = r['text']
cur = lambda n: repl.get(n, [post[n]])

EDITS = [
    (20, 'A hug, cuddle, kiss, or back rub should sometimes be allowed to end right there. If every affectionate touch '
         'becomes a bid for sex, affection itself can start feeling like pressure.',
         'A hug, cuddle, kiss, or back rub should sometimes be allowed to end right there, or she’ll start treating '
         'every touch like a sales pitch.',
     ['https://www.pangram.com/history/52ff7f0c-e151-4e8d-a553-fc4282ee3be5',
      'https://www.pangram.com/history/27c3b372-bc6e-4443-b057-e593fd1b9821'],
     'its last line, a Medium window of its own in his whole-article check, read AI-Generated by itself (the paragraph '
     'AI Detected, https://www.pangram.com/history/36aa6a6d-b5c1-4bba-8a68-129dcee268f9): a closing line that sounds '
     'wise and says the line before again (ways 6 and 16), joined to it and said plainly (way 8)'),
    (33, 'And then there’s the situationship, which is hard to define because that’s basically the point. Usually it’s a '
         'happenstance relationship based on sex.',
         'And then there’s the situationship, which is hard to define because that’s basically the point, but usually '
         'it’s a happenstance relationship based on sex.',
     ['https://www.pangram.com/history/722d3172-fb10-4237-97be-d89a690f5d31',
      'https://www.pangram.com/history/7ff558af-740d-40f9-8dcc-5475da271f17'],
     'its opening line, a Medium window of its own in his whole-article check: joined with ", but" to the sentence it '
     'introduces (way 8), his words kept'),
]
changes = []
for live, old, new, checks, why in EDITS:
    paras = cur(live)
    hits = [j for j, x in enumerate(paras) if x.count(old) == 1]
    assert len(hits) == 1, (live, hits)
    before = paras[hits[0]]
    assert '](' not in before, 'a link in the paragraph: put it back'
    changes.append({'card': 'R50-%d' % live, 'kind': 'para', 'live': live, 'before': before,
                    'after': [before.replace(old, new)], 'his_checks': checks, 'why': why})
(HERE / 'MINE-R50.json').write_text(json.dumps({
    'about': 'My tested changes of 2026-11-27 (r50): the two sentences his whole-article check of the r49 drafts read '
             'Medium, each a window of its own; a layer after r41/MINE-R41.json.', 'whose': 'mine',
    'changes': changes}, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
print('MINE-R50:', len(changes), 'changes:', [c['live'] for c in changes])

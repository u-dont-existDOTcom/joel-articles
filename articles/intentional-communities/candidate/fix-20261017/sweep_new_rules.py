"""The sweep of 2026-10-17 13:11 UTC: the six checks made from Joel's corrections that turn (tells_lint.py O41, O42, S1, S2, R2,
A2), run over every section of the article as it stands with this turn's drafts in place (article-with-drafts.md), each against
its published section (../original.md), the way a draft is linted (gate: "Each new rule is swept over the candidate sections in
the turn it's made"). His own words are his: the sections he wrote himself and every passage the owner-edits ledger records as
his ("words": "his") are passed as --owner lines and never flagged. S1 also runs over the whole article in reading order, since
a run of exclamations can cross a section break. Writes SWEEP-20261017.md and sweep-20261017.json here.
Run from candidate/: python3 fix-20261017/sweep_new_rules.py"""
import json, pathlib, re, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
C = HERE.parent
REPO = C.parents[2]
LINT = REPO / 'tools' / 'humanization' / 'tells_lint.py'
RULES = ('O41', 'O42', 'S1', 'S2', 'R2', 'A2')
art = (HERE / 'article-with-drafts.md').read_text(encoding='utf-8')
pub = (C.parent / 'original.md').read_text(encoding='utf-8')


def h1_sections(md):
    md = re.sub(r'<!--(?!\s*IMAGE).*?-->', '', md, flags=re.S)
    parts = re.split(r'(?m)^(?=# )', md)
    return [p.strip() for p in parts if p.startswith('# ')]


A, P = h1_sections(art), h1_sections(pub)
assert len(A) == len(P) == 17, (len(A), len(P))
# his own words: the ledger's "his" entries, and the sections he wrote himself (section 5's CANDIDATE note: "Joel's own text of
# 2026-10-06"; section 12 v12 and v13: his rewrite and his P2 and P3, "as written")
led = json.loads((C / 'OWNER-EDITS.json').read_text(encoding='utf-8'))['entries']
owner, locked = [], []
for e in led:
    if e.get('words') == 'his':
        owner += e.get('must_contain', []) + e.get('must_contain_exact', [])
    elif e.get('words') != 'proposed':
        # an older entry has no "words": its exact locks can hold his ruling on one word of a sentence of mine (section 8's
        # "boss is fine" locked "Older kids can't be allowed to quietly boss ..."), so a flag inside one is listed for his ruling
        locked += e.get('must_contain_exact', [])
HIS_SECTIONS = {'# The Medicine Part', '# The Math of Absorption'}
report, out = ['# Sweep of the checks made on 2026-10-17 13:11 (O41, O42, S1, S2, R2, A2)', '',
               'Each section of the article with this turn\'s drafts in place, linted against its published section. His own '
               'words (the sections he wrote and the ledger\'s "his" passages) are never flagged. Generated by '
               'fix-20261017/sweep_new_rules.py.', ''], {}
with tempfile.TemporaryDirectory() as d:
    d = pathlib.Path(d)
    for a, p in zip(A, P):
        head = a.split('\n', 1)[0]
        own = list(owner)
        if any(head.startswith(h) for h in HIS_SECTIONS):
            own += [b.strip() for b in re.split(r'\n\s*\n', a) if b.strip() and not b.startswith('#')]
        (d / 'draft.md').write_text(a + '\n', encoding='utf-8')
        (d / 'source.md').write_text(p + '\n', encoding='utf-8')
        (d / 'owner.txt').write_text('\n'.join(re.sub(r'\s+', ' ', x) for x in own) + '\n', encoding='utf-8')
        r = subprocess.run([sys.executable, str(LINT), str(d / 'draft.md'), '--source', str(d / 'source.md'), '--owner',
                            str(d / 'owner.txt')], capture_output=True, text=True, env={'TELLS_LINT_PARSE': '0', 'PATH': '/usr/bin:/bin'})
        flags, cur = [], None
        for line in r.stdout.split('\n'):
            m = re.match(r'^-- (\S+) ', line)
            if m:
                cur = m.group(1) if m.group(1) in RULES else None
                rule_text = line[3:]
                continue
            if cur and line.startswith('   * '):
                flags.append({'rule': cur, 'what': rule_text[:200], 'text': line[5:]})
        out[head] = flags
        for f in flags:
            if any(f['text'][:60] in L or L[:60] in f['text'] for L in locked):
                f['locked'] = 'inside a ledger lock: read the ruling behind it before changing it'
        report += ['## ' + head[2:], '']
        report += ['- %s: %s%s' % (f['rule'], f['text'], ' (%s)' % f['locked'] if f.get('locked') else '') for f in flags] or ['- nothing']
        report.append('')
# S1 across section breaks: the whole article in reading order, his words left out of the "mine" test
(d2 := pathlib.Path(tempfile.mkdtemp()))
body = '\n\n'.join(A)
(d2 / 'whole.md').write_text(body + '\n', encoding='utf-8')
(d2 / 'owner.txt').write_text('\n'.join(re.sub(r'\s+', ' ', x) for x in owner) + '\n', encoding='utf-8')
r = subprocess.run([sys.executable, str(LINT), str(d2 / 'whole.md'), '--owner', str(d2 / 'owner.txt')], capture_output=True, text=True,
                   env={'TELLS_LINT_PARSE': '0', 'PATH': '/usr/bin:/bin'})
s1 = [l[5:] for l in r.stdout.split('\n')[r.stdout.split('\n').index(next((x for x in r.stdout.split('\n') if x.startswith('-- S1')), '')) + 1:]
      if l.startswith('   * ')] if '-- S1' in r.stdout else []
report += ['## The whole article, S1 across section breaks', ''] + (['- ' + x for x in s1] or ['- nothing']) + ['']
out['whole article S1'] = s1
(HERE / 'SWEEP-20261017.md').write_text('\n'.join(report), encoding='utf-8')
(HERE / 'sweep-20261017.json').write_text(json.dumps(out, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
print('\n'.join(report))

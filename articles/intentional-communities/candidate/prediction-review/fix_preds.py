#!/usr/bin/env python3
"""fix_preds.py - the scorecard's rows from the PREDICTIONS.md files of the fix-* folders (2026-10-14) and of the
section batch folders `s*/bNNN/` (2026-10-15).

From 2026-10-14 the lane's predictions are in `fix-YYYYMMDD*/PREDICTIONS.md`: a "## Batch NNNg" heading, a table
"| text | mine | why |" (or with a fourth column, "Pangram", filled after the call), and, under it, a line
"Results of NNNg ...: KEY **result**, HH:MM:SS; KEY **result**, ...". scorecard.py reads only tables named
`s*/PREDICTIONS-*.md` whose rows are "NNNg-KEY" with a Pangram column, so the turn's 48 calls of 2026-10-14 morning
never reached the scorecard (the handoff of 2026-10-14 noted it). This writes, next to each fix folder's file,
`PREDICTIONS-scored.md` in the scorecard's format; scorecard.py reads those too.

  python3 prediction-review/fix_preds.py      # from candidate/
"""
import glob, os, re

C = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def results(text):
    """KEY -> result, from every 'Results of NNNg' line (bold result after the key)."""
    out = {}
    for line in text.split('\n'):
        if not line.startswith('Results of '):
            continue
        for k, r in re.findall(r'([A-Za-z0-9][\w.-]*) \*\*(.+?)\*\*', line):
            r = r.strip().strip('"').replace('"', '')
            out.setdefault(k, r)
    return out


def convert(path):
    text = open(path, encoding='utf-8').read()
    res = results(text)
    rows, batch = [], None
    col = {'mine': 1, 'why': 2, 'res': 3, 'chance': None}   # the old tables' order; a header row says otherwise
    for line in text.split('\n'):
        m = re.match(r'## Batch (\d+)g', line)
        if m:
            batch = m.group(1)
            continue
        if not batch or not line.startswith('|'):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        low = [c.lower() for c in cells]
        if low and low[0] == 'text':
            # 2026-10-18: a "chance" column (the call's chance of a 100% Human result) can sit anywhere in the table
            col = {'mine': low.index('mine') if 'mine' in low else 1,
                   'why': next((k for k, c in enumerate(low) if c.startswith('why')), 2),
                   'res': next((k for k, c in enumerate(low) if c.startswith('pangram')), 3),
                   'chance': next((k for k, c in enumerate(low) if c.startswith('chance')), None)}
            continue
        if not cells or cells[0] == '' or re.fullmatch(r':?-+:?', cells[0]):
            continue
        key = re.sub(r'[*`]', '', cells[0]).strip()
        got = cells[col['res']] if len(cells) > col['res'] and cells[col['res']] else res.get(key, '')
        got = re.sub(r'\*', '', got).replace('"', '').strip()
        if not got:
            continue
        ch = cells[col['chance']] if col['chance'] is not None and len(cells) > col['chance'] else ''
        rows.append('| %sg-%s | %s | %s | %s | %s |' % (batch, key, cells[col['mine']], ch, cells[col['why']].replace('|', '/'), got))
    out = os.path.join(os.path.dirname(path), 'PREDICTIONS-scored.md')
    head = ('# Predictions scored (generated by prediction-review/fix_preds.py from PREDICTIONS.md; do not edit)\n\n'
            '| text | mine | chance | why | Pangram |\n|---|---|---|---|---|\n')
    open(out, 'w', encoding='utf-8').write(head + '\n'.join(rows) + '\n')
    return out, len(rows)


if __name__ == '__main__':
    # 2026-10-15 on, section 13's batches have their own folders (s13/b288/ ...), same format
    for p in sorted(glob.glob(os.path.join(C, 'fix-*', 'PREDICTIONS.md'))) + sorted(glob.glob(os.path.join(C, 's*', 'b[0-9]*', 'PREDICTIONS.md'))) \
            + sorted(glob.glob(os.path.join(C, 'fix-*', 'b[0-9]*', 'PREDICTIONS.md'))):   # 2026-10-17: a turn's batches in its fix folder
        out, n = convert(p)
        print(os.path.relpath(out, C), n, 'rows')
